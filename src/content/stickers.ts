/**
 * Letakkan jawaban benar (o[0]) pada posisi `pos`, sisanya mengikuti urutan tulis.
 * Posisi diputar menurut urutan stiker, jadi jawaban benar tidak selalu di pilihan pertama.
 */
function arrange(o: [string, string, string], pos: number): string[] {
  const texts = [o[1], o[2]];
  texts.splice(pos, 0, o[0]);
  return texts;
}

function buildQuiz(s: StickerSeed, pos: number): Question {
  const j = arrange(s.junior.o, pos);
  const p = arrange(s.pro.o, pos);
  const explainIncorrect: Record<string, { junior: string; pro: string }> = {};
  for (let idx = 0; idx < 3; idx += 1) {
    if (idx === pos) continue;
    explainIncorrect[`opt-${idx}`] = { junior: s.junior.redo, pro: s.pro.redo };
  }
  return {
    id: `stk-q-${s.id}`,
    type: 'mcq',
    difficulty: 1,
    prompt: { junior: s.junior.q, pro: s.pro.q },
    choices: [0, 1, 2].map((idx) => ({
      id: `opt-${idx}`,
      label: { junior: j[idx]!, pro: p[idx]! },
    })),
    answer: `opt-${pos}`,
    hints: [{ junior: s.junior.h, pro: s.pro.h }, undefined],
    explainCorrect: { junior: s.junior.why, pro: s.pro.why },
    explainIncorrect,
    tags: [s.id],
  };
}

