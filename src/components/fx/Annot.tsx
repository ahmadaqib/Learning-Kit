import React from 'react';

export interface AnnotProps {
  children: React.ReactNode;
  /**
   * Set this when the annotation carries information ("kamu di sini"). The visible text is then
   * aria-hidden and `label` is rendered as visually hidden plain text. Without it the annotation is decorative
   * and entirely aria-hidden.
   */
  label?: string;
  /** Optional one-shot entrance. 'note' is the halfway pop (M50), 'fade' and 'rise' are quiet reveals. */
  effect?: 'none' | 'note' | 'fade' | 'rise';
  /** Start time inside a sequence, Junior ms. */
  at?: number;
  className?: string;
  style?: React.CSSProperties;
}

const EFFECT_CLASS: Record<NonNullable<AnnotProps['effect']>, string> = {
  none: '',
  note: 'pw-fx-note',
  fade: 'pw-fx-fade',
  rise: 'pw-fx-rise',
};

/**
 * Bito's annotation slot: one `.pw-note` element. The skin is pure CSS: handwriting in Junior,
 * a `// code comment` in Pro (the prefix is generated by CSS and is not read by screen readers).
 * At most five words, at most two per screen, never required content (spec 4.4).
 */
export const Annot: React.FC<AnnotProps> = ({ children, label, effect = 'none', at, className = '', style }) => {
  const classes = ['pw-note', EFFECT_CLASS[effect], className].filter(Boolean).join(' ');
  const mergedStyle = at !== undefined ? ({ ...style, '--at': `${at}ms` } as React.CSSProperties) : style;

  if (label) {
    return (
      <>
        <span className={classes} style={mergedStyle} aria-hidden="true">
          {children}
        </span>
        <span className="visually-hidden">{label}</span>
      </>
    );
  }
  return (
    <span className={classes} style={mergedStyle} aria-hidden="true">
      {children}
    </span>
  );
};
